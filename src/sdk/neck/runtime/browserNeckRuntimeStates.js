/**
 * @param {unknown} state
 * @returns {string}
 */
export function normalizeBrowserNeckRuntimeState(state) {
  const s = String(state || "").toUpperCase()
  if (KNOWN.has(s)) return s
  return BROWSER_NECK_RUNTIME_STATES.DISCONNECTED
}

/**
 * @param {string} from
 * @param {string} to
 * @returns {boolean}
 */
export function isBrowserNeckRuntimeTransitionAllowed(from, to) {
  const a = normalizeBrowserNeckRuntimeState(from)
  const b = normalizeBrowserNeckRuntimeState(to)
  if (a === b) return true
  const allowed = BROWSER_NECK_RUNTIME_TRANSITIONS[a]
  return Array.isArray(allowed) && allowed.includes(b)
}

/**
 * Motion-emitting states (periodic 0x32 hold / run / calibration preview).
 * @param {string} state
 */
export function isBrowserNeckRuntimeMotionActive(state) {
  const s = normalizeBrowserNeckRuntimeState(state)
  return (
    s === BROWSER_NECK_RUNTIME_STATES.RUNNING ||
    s === BROWSER_NECK_RUNTIME_STATES.HOLD ||
    s === BROWSER_NECK_RUNTIME_STATES.STALE_SAFE_HOLD ||
    s === BROWSER_NECK_RUNTIME_STATES.ENABLED ||
    s === BROWSER_NECK_RUNTIME_STATES.CALIBRATING_NEUTRAL
  )
}

/**
 * Accepts animation / timeline targets?
 * Frozen while CALIBRATING_NEUTRAL (R4.1).
 * @param {string} state
 */
export function canAcceptBrowserNeckAnimationTarget(state) {
  const s = normalizeBrowserNeckRuntimeState(state)
  return (
    s === BROWSER_NECK_RUNTIME_STATES.RUNNING ||
    s === BROWSER_NECK_RUNTIME_STATES.HOLD ||
    s === BROWSER_NECK_RUNTIME_STATES.ENABLED
  )
}

/**
 * @param {string} state
 */
export function isBrowserNeckCalibratingNeutral(state) {
  return normalizeBrowserNeckRuntimeState(state) === BROWSER_NECK_RUNTIME_STATES.CALIBRATING_NEUTRAL
}
