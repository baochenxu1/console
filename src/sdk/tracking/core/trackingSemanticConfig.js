function mergeSection(base, override) {
  return { ...base, ...(override && typeof override === "object" ? override : {}) }
}

export function normalizeTrackingSemanticConfig(config = {}) {
  const d = DEFAULT_TRACKING_SEMANTIC_CONFIG
  return {
    ...d,
    ...config,
    neutral: mergeSection(d.neutral, config.neutral),
    gains: mergeSection(d.gains, config.gains),
    invert: mergeSection(d.invert, config.invert),
    deadzone: mergeSection(d.deadzone, config.deadzone),
    smoothing: mergeSection(d.smoothing, config.smoothing),
    eye: mergeSection(d.eye, config.eye),
    brow: mergeSection(d.brow, config.brow),
    lip: mergeSection(d.lip, config.lip),
    lipGeometry: mergeSection(d.lipGeometry, config.lipGeometry),
    jawGeometry: mergeSection(d.jawGeometry, config.jawGeometry),
    noseAnchor: mergeSection(d.noseAnchor, config.noseAnchor),
    mouthScenario: mergeSection(d.mouthScenario, config.mouthScenario),
    browGate: mergeSection(d.browGate, config.browGate),
    mouthCorner: mergeSection(d.mouthCorner, config.mouthCorner),
    gaze: mergeSection(d.gaze, config.gaze),
    gazeV2: mergeSection(d.gazeV2, config.gazeV2),
    gazeAlgorithm: config.gazeAlgorithm ?? d.gazeAlgorithm,
  }
}
